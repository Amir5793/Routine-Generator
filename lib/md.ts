/* ════════ تولید Markdown (خروجی روتین) ════════
   Ported 1:1 from buildMD() in the original HTML. */

import type { Draft, Week } from "./types";
import {
  BREC,
  DAYS,
  LADDER,
  MISSION,
  REVIEWS,
  SACRIFICE,
  SUBJECTS,
  dayName,
} from "./data";
import { analysisLabel, capacity, loads, totK, totL } from "./engine";
import { fa, r5 } from "./format";

export function buildMD(d: Draft, weeks: Week[]): string {
  const q = (id: string) => d.quotas[id];
  const mk = (id: string, f: number) =>
    `L ${fa(r5(Number(q(id).L) * f))} / K ${fa(r5(Number(q(id).K) * f))}`;
  const a = analysisLabel(d, weeks);
  const src = a.txt;
  const ex = d.mode === "exam";
  const e = d.events;
  const hol = (k: "sat" | "sun" | "mon" | "tue" | "wed") => e.holidays[k];
  const out: string[] = [];
  out.push(
    `# روتین هفتهٔ ${fa(d.n)}${d.startDate ? " — " + d.startDate : ""}`,
    "",
    `> فاز ${fa(d.phase)} · هفتهٔ ${ex ? "آزمون ماز" : "بدون آزمون ماز"} · چارچوب v2.0`,
    "",
    `> تولیدشده با مولد روتین — مقادیر متغیر همین هفته اینجاست؛ قواعد ثابت در چارچوب.`,
    "",
  );
  out.push(
    `## ۰) وضعیت ورودی و روند`,
    "",
    `| شاخص | هفتهٔ قبل | هدف این هفته |`,
    `|---|---|---|`,
    `| اجرای K | ${d.status.k !== "" ? fa(d.status.k) + "٪" : "—"} | ≥۷۵٪ |`,
    `| بک‌لاگ فیزیک | ${fa(d.status.backlog)} | ${Number(d.status.backlog) > 0 ? "کاهش حداقل ۴۰٪" : "صفر ماندن"} |`,
    `| انرژی میانگین | ${d.status.energy !== "" ? fa(d.status.energy) : "—"} | ≥۳.۵ |`,
    `| روزهای L-کامل | ${d.status.lDays !== "" ? fa(d.status.lDays) + " از ۷" : "—"} | ≥۶ |`,
    "",
  );
  const debts: string[] = [];
  if (d.status.debts.a) debts.push("مرور A جامانده");
  if (d.status.debts.b) debts.push("ضبط B جامانده");
  if (d.status.debts.an) debts.push("تحلیل جامانده");
  out.push(`بدهی‌های ورودی: ${debts.length ? debts.join(" · ") : "ندارد ✓"}`);
  if (d.status.note) out.push(`یادداشت: ${d.status.note}`);
  out.push("");
  out.push(
    `## ۱) قفل‌های هفته (تغییرناپذیر)`,
    "",
    `- خواب 23:30–06:30 (هر شب)`,
    `- کلاس‌های A زنده: شنبه فیزیک 22:00 · یکشنبه حسابان 16:45 · دوشنبه فیزیک 16:45 / فارسی 18:30 / شیمی 20:15 · سه‌شنبه دینی 18:30 · چهارشنبه هندسه 16:45`,
    `- پخش‌های B نادیده گرفته می‌شوند (ضبط بعداً): یکشنبه زمین/عربی · سه‌شنبه آمار`,
    `- زبان C شنبه ← ${d.langCut ? "حذف این هفته (طبق تعریف C)" : "اختیاری — بدون گرفتن وقت از خواب، A و کارهای ضروری"}`,
  );
  if (ex)
    out.push(`- آزمون ماز: جمعه، شروع ثابت 08:00، مدت ۳ ساعت (بازهٔ مجاز شرکت 08:00–15:00)`);
  if (e.asatide) out.push(`- آزمون اساتید: ${dayName(e.asatideDay)} ${e.asatideTime}`);
  for (const k of ["sat", "sun", "mon", "tue", "wed"] as const)
    if (hol(k))
      out.push(
        `- تعطیلی مدرسه ${dayName(k)} — زنگ‌های این روز طبق قاعدهٔ جابه‌جایی به اسلات باز منتقل می‌شوند`,
      );
  if (e.schoolExam)
    out.push(`- هفتهٔ امتحان مدرسه: بار سبک — Lها محفوظ، Kها بر حسب ظرفیت واقعی`);
  out.push(
    `- ورزش چهارشنبه بلاعوض · جمعه ۸ ساعت استراحت`,
    `- مدرسه: شنبه عربی (زنگ ۳) و یکشنبه تاریخ (زنگ ۲) گوش + جزوه · دوشنبه زنگ آخر استراحت`,
    "",
  );
  out.push(
    `## ۲) جای‌گذاری چهار اصل`,
    "",
    `### مرورهای A (اصل ۲ — سقف ۴۸ ساعت)`,
    "",
    `| کلاس A | پایان | مهلت مرور | جای مرور |`,
    `|---|---|---|---|`,
    REVIEWS.map((r) => `| ${r[0]} ${r[1]} | ${r[2]} | ${r[3]} | ${r[4]} |`).join("\n"),
    "",
    `### ضبط‌های B (اصل ۱ — پیش از جلسهٔ بعدی)`,
    "",
    `| ضبط | پخش | مهلت | جای تماشا |`,
    `|---|---|---|---|`,
    BREC.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} | ${r[3]} |`).join("\n"),
    "",
    `### منبع تحلیل شنبه (اصل ۳)`,
    `شنبه ← ${src} (زمان دقیق: 14:30–16:30، L 60′ / K 120′ + دفتر خطا)`,
    "",
    `### قاعدهٔ یک روز اختلال (اصل ۴)`,
    `C حذف ← B به مهلت بعدی ← A و خواب محفوظ ← جبران در پنجشنبه/جمعه با ظرفیت واقعی؛ سهمیه‌ها بدون محاسبهٔ دوباره به روز بعد منتقل نمی‌شوند.`,
    d.sultanApplied
      ? `> فرمانروا: سهمیه‌های این هفته ۲۰٪ کاهش یافت (دو هفتهٔ متوالی K<۶۰٪).`
      : "",
    "",
  );
  out.push(
    `## ۳) سهمیه‌های هفته (L/K)`,
    "",
    `| درس | L | K |`,
    `|---|---|---|`,
    SUBJECTS.map((s) => `| ${s.n} | ${fa(q(s.id).L)} | ${fa(q(s.id).K)} |`).join("\n"),
    `| **جمع** | **${fa(totL(d))}** | **${fa(totK(d))}** |`,
    "",
    `قواعد: تحلیل غلط‌ها همان روز · ثبت دفتر خطا (بی‌دقتی/مفهومی/زمانی) · تمرین با تایمر زمان استاندارد (فاز ۱) · تست بدون تحلیل نصف شمرده می‌شود · K ≥ L برای هر درس.`,
    "",
  );
  const B = (t: string, x: string) => out.push(`- **${t}** — ${x}`);
  out.push(`## ۴) نقشهٔ روزها`, "");
  out.push(`### شنبه — مأموریت: ${MISSION.sat}`);
  B(
    "مدرسه",
    (hol("sat")
      ? "تعطیل — بک‌لاگ به اسلات باز (نردبان):"
      : "عربی زنگ ۳ گوش+جزوه (قفل) · زنگ‌های ۱/۲/۴ ← تست بک‌لاگ فیزیک") +
      ` (${mk("phyBack", 0.75)})`,
  );
  B("14:30–16:30", `تحلیل ${src} (L 60′ / K 120′ + دفتر خطا)`);
  B(
    "16:45–18:15",
    d.langCut ? "زبان C — حذف این هفته ← سرریز تحلیل یا استراحت" : "زبان C (اختیاری)",
  );
  B("18:15–19:30", "شام / استراحت");
  B(
    "19:30–21:30",
    `تحلیل تست‌های بک‌لاگ (${mk("phyBack", 0.25)}) + عربی (${mk("arabic", 0.35)})`,
  );
  B("22:00–23:30", "فیزیک A — زنده");
  B("23:30", "مرور ذهنی در تخت (۳ ایدهٔ فیزیک) ← خواب");
  out.push("");
  out.push(`### یکشنبه — مأموریت: ${MISSION.sun}`);
  B(
    "مدرسه",
    (hol("sun")
      ? "تعطیل — حسابان به اسلات باز:"
      : "تاریخ زنگ ۲ نکته‌برداری (قفل) · زنگ‌های ۱/۳/۴ ← تست حسابان") +
      ` (${mk("calc", 0.6)})`,
  );
  B("14:00–16:30", "ناهار / استراحت / روتین (قفل)");
  B("16:45–20:00", "حسابان A");
  B("20:00–20:45", "مرور لحظه‌ای حسابان (قلم اصل ۲)");
  B("20:45–21:45", `تست حسابان (${mk("calc", 0.4)})`);
  B("22:15–23:15", `عربی عمومی (${mk("arabic", 0.35)})`);
  B("23:30", "خواب — پخش زندهٔ زمین/عربی نادیده (طبق چارچوب)");
  out.push("");
  out.push(`### دوشنبه — مأموریت: ${MISSION.mon}`);
  B(
    "مدرسه",
    (hol("mon")
      ? "تعطیل — بار به اسلات‌های باز طبق نردبان:"
      : "زنگ ۱/۳ ← مرور فیزیک شنبه (۱۵′) + تست فیزیک جاری") +
      ` (${mk("phy", 0.5)}) · زنگ ۲ ← فارسی (${mk("farsi", 0.7)}) · زنگ ۴ ← استراحت (قفل)`,
  );
  B("15:00–16:45", "روتین / استراحت (قفل)");
  B("16:45–18:15", "فیزیک A · 18:30–20:00 فارسی A");
  B("20:00–20:15", "پیش‌خوانی ۱۰′ سرفصل شیمی");
  B("20:15–23:15", "شیمی A (با میکروبریک)");
  B("23:15", "مرور ذهنی در تخت (۳ ایدهٔ شیمی) ← خواب");
  out.push("");
  out.push(`### سه‌شنبه — مأموریت: ${MISSION.tue}`);
  B(
    "مدرسه",
    (hol("tue") ? "تعطیل — ضبط‌ها به چهارشنبه (پیش از مهلت):" : "زنگ‌ها ← شیمی") +
      ` (${mk("chem", 1)}) + مرور/تست فیزیک دوشنبه (${mk("phy", 0.5)}) + هندسه (${mk("geo", 0.2)})`,
  );
  B("17:00–18:15", "مرور کامل شیمی دوشنبه + ۱۰ تست (قلم اصل ۲)");
  B("18:30–20:00", "دینی A");
  B("20:00–20:45", "ضبط عربی B (سرعت ۲)");
  B("20:45–21:30", "ضبط زمین B (سرعت ۲)");
  B("21:30–23:00", `عمومی میکرو (املا ۱۰′ + دینی ${mk("din", 0.6)}) + جامانده‌ها`);
  B("23:30", "خواب");
  out.push("");
  out.push(`### چهارشنبه — مأموریت: ${MISSION.wed}`);
  B(
    "مدرسه",
    (hol("wed") ? "تعطیل — هندسه به اسلات باز:" : "ورزش زنگ ۱ بلاعوض · زنگ ۲/۳ ← تست هندسه") +
      ` (${mk("geo", 0.45)})`,
  );
  B("15:00–16:45", "روتین (قفل) · 16:45–18:15 هندسه A");
  B("18:15–19:00", "شام / استراحت");
  B("19:00–19:30", "مرور فارسی دوشنبه (قلم اصل ۲)");
  B("19:30–21:00", `تست هندسه (${mk("geo", 0.35)})`);
  B("21:00–22:30", `باز — نردبان (پیش‌فرض: عربی ${mk("arabic", 0.3)} / فارسی ${mk("farsi", 0.3)})`);
  B("23:30", "خواب");
  out.push("");
  out.push(`### پنجشنبه — مأموریت: ${MISSION.thu}`);
  B("07:30–09:00", "مرور فاصله‌دار ۷/۳۰ (L 45′ / K 90′)");
  B("09:00–12:00", e.asatide ? `آزمون اساتید (${e.asatideTime})` : "باز — نردبان");
  B("12:00–14:00", "ناهار / استراحت");
  B("14:00–14:45", "ضبط آمار B (سرعت ۲)");
  B("14:45–15:15", "مرور دینی (اصل ۲) · 15:30–16:00 مرور هندسه (اصل ۲)");
  B(
    "16:15–17:00",
    ex ? "آمادگی سبک آزمون ماز (دفتر خطا + سرفصل‌های اعلامی)" : "جبران و بدهی‌ها طبق نردبان",
  );
  B("17:00–19:00", "استراحت / زمان شخصی");
  B("19:00–19:45", `جمع‌بندی هفتهٔ ${fa(d.n)} + پیش‌نویس روتین هفتهٔ ${fa(d.n + 1)}`);
  B(
    "19:45–21:30",
    "باز — نردبان (جبران Kهای ناتمام" + (!d.langCut ? " · زبان" : "") + ")",
  );
  B("21:30–23:30", ex ? "استراحت + آماده‌سازی صبح آزمون (صبحانه، میز، خودکار)" : "استراحت");
  out.push("");
  out.push(`### جمعه — مأموریت: ${MISSION.fri}`);
  if (ex) {
    B("06:30", "بیداری · 07:00–07:45 صبحانهٔ کامل + ۱۰′ گرم‌کردن ذهن");
    B("08:00–11:00", "آزمون ماز (شروع ثابت 08:00)");
    B("11:00–11:30", "مرور داغ: فقط سؤال‌های علامت‌دار");
    B("11:30–19:30", "۸ ساعت استراحت (قفل)");
    B("19:30–23:30", "اختیاریِ سبک یا هیچ · 23:30 خواب");
    out.push(`- ← شنبه: تحلیل کامل این آزمون = ورودی هفتهٔ ${fa(d.n + 1)}`);
  } else {
    B("کل روز", "۸ ساعت استراحت (قفل) + زمان شخصی");
    B("اسلات‌های اختیاری", "بدهی/بک‌لاگ طبق نردبان — بدون اجبار");
    out.push(
      `- ← منبع تحلیل شنبهٔ بعد، هنگام پیش‌نویس هفتهٔ ${fa(d.n + 1)} مشخص شود (اصل ۳)`,
    );
  }
  out.push("");
  out.push(`## ۵) نردبان اسلات باز`, LADDER.join(" · "), "");
  out.push(
    `## ۶) قربانی‌های این هفته (ترتیب حذف Kها)`,
    SACRIFICE.join(" ← ") + `. هیچ L و هیچ مهلت بخش ۲ در این فهرست نیست.`,
    "",
  );
  out.push(
    `## ۷) رصد روزانه (هر شب ۳۰ ثانیه)`,
    "",
    `| روز | L کامل؟ | K ٪ | انرژی /۵ | یک خط واقعیت |`,
    `|---|---|---|---|---|`,
    DAYS.map((x) => `| ${x.n} | ☐ | | | |`).join("\n"),
    "",
  );
  out.push(
    `## ۸) جمع‌بندی هفتگی (پنجشنبه شب)`,
    `۱. کدام Lها ناتمام ماندند و چرا؟ ۲. K واقعی چند ٪ شد؟ (<۶۰٪ ← هفتهٔ بعد ۱۵٪ کم) ۳. بک‌لاگ فیزیک: عدد پایانی؟ ۴. بزرگ‌ترین الگوی خطا؟ ۵. یک چیز که هفتهٔ بعد عوض می‌کنم: ____`,
    "",
  );
  out.push(
    `## ۹) چک‌لیست سازگاری با چارچوب`,
    `- [x] هر ضبط B جای و مهلت دارد (بخش ۲)`,
    `- [x] هر کلاس A مروری ≤۴۸ ساعت دارد (بخش ۲)`,
    `- [x] منبع تحلیل شنبه: ${src}`,
    `- [x] ترتیب اختلال مشخص است (بخش ۲ و ۶)`,
    `- [x] بک‌لاگ فیزیک عدد دارد: ${fa(d.status.backlog)}`,
    `- [x] خواب 23:30–06:30 و ۸ ساعت جمعه نقض نشده`,
    "",
    `*قاعدهٔ جابه‌جایی: اگر اسلاتی از دست رفت، همان قلم اولین اسلات باز طبق نردبان می‌رود — نه قلم بعدی.*`,
    `*منبع: چارچوب v2.0 · مولد روتین Weekly OS*`,
  );
  return out.filter((x) => x !== undefined).join("\n");
}
